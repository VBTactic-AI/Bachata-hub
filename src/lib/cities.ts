import { unstable_cache } from "next/cache";
import { prisma } from "./prisma";

export const CITIES_CACHE_TAG = "active-cities";

// Список активных городов нужен шапке сайта (CitySwitcher) — то есть
// выполнялся на КАЖДОЙ загрузке любой страницы, отдельным round-trip'ом к
// удалённой БД (замерено через pg_stat_statements, 2026-09-08: 10 260
// вызовов этого запроса, при 6 строках в таблице).
//
// Почему кэш здесь безопасен и как инвалидируется (CLAUDE.md — кэш только с
// понятной инвалидацией): это справочник, а не состояние соревнования.
// В приложении НЕТ ни одного пути, который меняет City — проверено grep'ом
// (prisma.city.create/update/delete не вызывается нигде), города заводятся
// только через prisma/seed.ts или правку в БД. Поэтому единственный
// реальный источник изменений — деплой/сид, и revalidate: 300 гарантирует,
// что список подхватится максимум через 5 минут без всякого кода.
// CITIES_CACHE_TAG выставлен заранее: если когда-нибудь появится админка
// городов, ей достаточно вызвать revalidateTag(CITIES_CACHE_TAG), чтобы
// сброс стал мгновенным.
//
// Сознательно НЕ кэшируем так ничего из движка соревнований (жеребьёвка,
// оценки, результаты, статусы) — там устаревшие данные означали бы неверное
// решение на паркете.
export const getActiveCities = unstable_cache(
  async () => prisma.city.findMany({ where: { isActive: true }, orderBy: { nameRu: "asc" } }),
  ["active-cities"],
  { tags: [CITIES_CACHE_TAG], revalidate: 300 }
);
