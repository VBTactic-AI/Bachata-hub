// Цвета-метки категорий в /admin (сайдбар "Судьи", лента категорий в
// "Мониторе"). Фиксированный семантический набор поверх admin-*, а не токены
// темы: цвет здесь только различает категории между собой и не обязан
// меняться вместе с темой. Один список на все экраны — чтобы одна и та же
// категория была одного цвета везде, где организатор её видит.
export const CATEGORY_DOT_COLORS = ["#3b82f6", "#22c55e", "#a78bfa", "#fb923c", "#f87171", "#facc15", "#22d3ee", "#f472b6"];

export function categoryDotColor(index: number): string {
  return CATEGORY_DOT_COLORS[index % CATEGORY_DOT_COLORS.length];
}
