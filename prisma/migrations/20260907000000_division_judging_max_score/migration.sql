-- квотой по числу проходящих) — задаётся один раз при создании дивизиона,
-- используется generateRounds() как значение Round.judgingMaxScore для
-- каждого создаваемого раунда. Существующие дивизионы получают дефолт 1 —
-- совпадает с их текущим фактическим поведением (Round.judgingMaxScore тоже
-- по умолчанию 1, явно нигде не задавался до этой миграции).

ALTER TABLE "Division" ADD COLUMN "judgingMaxScore" INTEGER NOT NULL DEFAULT 1;
