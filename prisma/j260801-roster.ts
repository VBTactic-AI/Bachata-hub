import type { Gender } from "@prisma/client";

export type Person = { displayName: string; gender: Gender };

const CYRILLIC_MAP: Record<string, string> = {
  а: "a", б: "b", в: "v", г: "g", д: "d", е: "e", ё: "e", ж: "zh", з: "z",
  и: "i", й: "y", к: "k", л: "l", м: "m", н: "n", о: "o", п: "p", р: "r",
  с: "s", т: "t", у: "u", ф: "f", х: "h", ц: "ts", ч: "ch", ш: "sh", щ: "sch",
  ъ: "", ы: "y", ь: "", э: "e", ю: "yu", я: "ya",
};

export function slugifyName(name: string): string {
  return name
    .toLowerCase()
    .split("")
    .map((ch) => CYRILLIC_MAP[ch] ?? ch)
    .join("")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

export function emailFor(prefix: string, p: Person): string {
  return `${prefix}-${slugifyName(p.displayName)}@bachata.by`;
}

function leaders(names: string[]): Person[] {
  return names.map((displayName) => ({ displayName, gender: "MALE" as const }));
}
function followers(names: string[]): Person[] {
  return names.map((displayName) => ({ displayName, gender: "FEMALE" as const }));
}

